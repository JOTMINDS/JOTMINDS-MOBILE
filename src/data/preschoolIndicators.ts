export const INDICATORS_BY_ID: Record<string, DevelopmentalIndicator> = MASTER_PRESCHOOL_INDICATORS.reduce(
  (acc, ind) => {
    acc[ind.id] = ind;
    return acc;
  },
  {} as Record<string, DevelopmentalIndicator>
);

export const INDICATORS_BY_DOMAIN: Record<DevelopmentalDomainCode, DevelopmentalIndicator[]> = MASTER_PRESCHOOL_INDICATORS.reduce(
  (acc, ind) => {
    if (!acc[ind.domainCode]) acc[ind.domainCode] = [];
    acc[ind.domainCode].push(ind);
    return acc;
  },
  {} as Record<DevelopmentalDomainCode, DevelopmentalIndicator[]>
);

export function getIndicatorsByBandAndDomain(
  band: DevelopmentalBand,
  domainCode?: DevelopmentalDomainCode
): DevelopmentalIndicator[] {
  return MASTER_PRESCHOOL_INDICATORS.filter(ind => {
    const matchesDomain = !domainCode || ind.domainCode === domainCode;
    const matchesBand =
      ind.band === band ||
      (band === 'P1' && ind.band.includes('P1')) ||
      (band === 'P2' && ind.band.includes('P2')) ||
      (band === 'P3' && ind.band.includes('P3')) ||
      (band === 'P4' && ind.band.includes('P4'));
    return matchesDomain && matchesBand;
  });
}
